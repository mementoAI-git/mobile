import { describe, expect, test } from 'bun:test';
import { readFileSync } from 'node:fs';
const { quoteScriptPaths } = require('../../../plugins/with-ios-script-paths');

describe('iOS bundling script paths', () => {
  test('repairs phases generated by Sentry during a clean prebuild', async () => {
    const withRepair = require('../../../plugins/with-ios-script-paths');
    const { withSentryIOS } = require('@sentry/react-native/plugin/build/withSentryIOS');
    const plugins = JSON.parse(readFileSync('app.json', 'utf8')).expo.plugins.map((entry: string | [string, unknown]) => Array.isArray(entry) ? entry[0] : entry);
    let config = { name: 'Memento', slug: 'memento' } as any;
    for (const name of plugins) {
      if (name === './plugins/with-ios-script-paths') config = withRepair(config);
      if (name === '@sentry/react-native/expo') config = withSentryIOS(config, '');
    }
    const phases: Record<string, { shellScript: string }> = {
      'Bundle React Native code and images': { shellScript: JSON.stringify('`node --print "react-native/scripts/react-native-xcode.sh"`') },
    };
    const project = {
      pbxItemByComment: (name: string) => phases[name],
      addBuildPhase: (_files: unknown[], _type: string, name: string, _target: unknown, options: { shellScript: string }) => {
        phases[name] = { shellScript: JSON.stringify(options.shellScript) };
      },
    };
    await config.mods.ios.xcodeproj({ ...config, modResults: project, modRequest: {} });
    for (const phase of Object.values(phases)) {
      const script = JSON.parse(phase.shellScript);
      expect(script).not.toContain('`');
      expect(script).toContain('"$(');
    }
  });
  test('quotes Sentry and React Native command substitutions as individual paths', () => {
    const script = '/bin/sh `"$NODE_BINARY" --print "sentry-path"` `"$NODE_BINARY" --print "react-native-path"`\n';
    expect(quoteScriptPaths(script)).toBe('/bin/sh "$("$NODE_BINARY" --print "sentry-path")" "$("$NODE_BINARY" --print "react-native-path")"\n');
  });
  test('does not add another layer of quotes on repeated prebuilds', () => {
    const script = '/bin/sh `node --print "sentry-path"`';
    const once = quoteScriptPaths(script);
    expect(quoteScriptPaths(once)).toBe(once);
  });
});
